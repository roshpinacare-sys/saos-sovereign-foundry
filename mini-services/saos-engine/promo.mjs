/**
 * promo.mjs — the promotion rail: one honest public report per UTC day.
 * The operator ordered "גם קידום" running without them — this rail publishes
 * the system's REAL measured numbers to the master account's blog. Nothing
 * invented, nothing promised — transparency IS the promotion.
 *
 * Guards: 1/day (existence-checked on-chain, not just state), posting-key
 * authority only, capped content, honest numbers only.
 */
import { rpcCall } from "./measure.mjs";
import { executeAs, masterAccount } from "./signer.mjs";

const dayOf = (iso) => String(iso ?? new Date().toISOString()).slice(0, 10).replace(/-/g, "");

function fmt(v, d = 2) { return v == null ? "?" : Number(v).toFixed(d); }

export async function postDailyReport({ obs, rollup, intel, now }) {
  const master = masterAccount();
  const day = dayOf(now);
  const permlink = `saos-transparency-${day}`;
  // on-chain existence check — the chain is the dedup source of truth
  const exists = await rpcCall("condenser_api.get_content", [master, permlink]);
  if (exists.ok && exists.result && exists.result.author) {
    return { verdict: "ALREADY-POSTED", permlink };
  }
  const parity = obs?.parity?.parity ?? null;
  const fills = obs?.fills ?? 0;
  const realized = rollup?.realizedSbd ?? null;
  const fuel = obs?.fuel?.fuelUsdPerDay ?? null;
  const author = obs?.fuel?.authorUsdPerDay ?? null;
  const orders = obs?.ordersOk ? (obs.orders?.length ?? 0) : null;
  const decisions = (intel?.decisions ?? []).map((d) => `- ${d.kind}: ${d.decision} (${d.reason})`).join("\n") || "- (none)";

  const title = "SAOS daily transparency report — real numbers, no promises";
  const body = [
    "**Measured on-chain this cycle — automated market-making system, publishing its own truth:**",
    "",
    `- Parity (SBD/STEEM): ${fmt(parity, 6)} (source: ${obs?.parity?.source ?? "?"}${obs?.parity?.lowConfidence ? ", low-confidence" : ""})`,
    `- Book: ${orders ?? "?"} open orders · ${fills} real fills in window`,
    `- Realized P&L (avg-cost, honest): ${fmt(realized, 6)} SBD`,
    `- Rails fuel measured: curation ${fmt(fuel, 4)} $/day · author ${fmt(author, 4)} $/day`,
    `- Soldier fleet: ${intel?.decisions?.some((d) => d.kind === "soldiers" && d.decision === "grids-live") ? "live on the book" : "deploying"}`,
    "",
    "**Today's autonomous decisions:**",
    decisions,
    "",
    "This post is generated by the system itself from its own measurements. The engine is keyless-doctrine: signing is doctrine-capped, all actions are journaled on-chain where anyone can verify. No profit is promised — only real numbers are published.",
    "",
    `permlink: ${permlink} · day: ${day}`,
  ].join("\n");

  const meta = JSON.stringify({ tags: ["steem", "defi", "saos", "transparency"], app: "saos-sovereign-engine" });
  const res = await executeAs(master, [[
    "comment",
    { parent_author: "", parent_permlink: "steem", author: master, permlink, title, body, json_metadata: meta },
  ]], { tag: "promo-daily", role: "posting" });
  return { ...res, permlink };
}
